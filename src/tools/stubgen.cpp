#include <iostream>
#include <fstream>
#include <string>
#include <vector>

std::string CleanFunctionName(std::string line) {
    size_t arrowPos = line.find("->");
    if (arrowPos != std::string::npos) {
        line = line.substr(arrowPos + 2);
    }

    size_t first = line.find_first_not_of(" \t\r\n");
    if (first == std::string::npos) return "";
    size_t last = line.find_last_not_of(" \t\r\n");
    return line.substr(first, (last - first + 1));
}

int main(int argc, char* argv[]) {
    if (argc < 3) {
        std::cout << "Usage: .\\stubgen.exe <input_list.txt> <output_stubs.cpp>" << std::endl;
        return 1;
    }

    std::ifstream inFile(argv[1]);
    if (!inFile) {
        std::cout << "[ERROR] Could not open input file: " << argv[1] << std::endl;
        return 1;
    }

    std::ofstream outFile(argv[2]);
    if (!outFile) {
        std::cout << "[ERROR] Could not create output file: " << argv[2] << std::endl;
        return 1;
    }

    outFile << "// AUTO-GENERATED BY STUBGEN.EXE\n";
    outFile << "#include <windows.h>\n";
    outFile << "#include <iostream>\n";
    outFile << "#include <cstdint>\n\n";
    outFile << "extern \"C\" {\n\n";

    std::string line;
    int count = 0;

    while (std::getline(inFile, line)) {
        std::string funcName = CleanFunctionName(line);

        if (funcName.empty() || funcName[0] == '[' || funcName[0] == '=' || funcName.rfind("Target:", 0) == 0 || funcName.rfind("Ordinal", 0) == 0) {
            continue;
        }

        outFile << "    __declspec(dllexport) int64_t " << funcName << "() {\n";
        outFile << "        std::cout << \"[STUB] Game called: " << funcName << "()\" << std::endl;\n";
        outFile << "        return 0; // S_OK\n";
        outFile << "    }\n\n";
        count++;
    }

    outFile << "} // extern \"C\"\n";

    std::cout << "[SUCCESS] Generated " << count << " Xbox stub functions into " << argv[2] << "!" << std::endl;
    return 0;
}